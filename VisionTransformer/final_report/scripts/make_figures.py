# ---- 2. learning-rate check (3 seeds): validation loss and test accuracy against the rate -----------------------
RATES = {"3e-6": 3e-6, "1e-5": 1e-5, "3e-5": 3e-5, "1e-4": 1e-4, "3e-4": 3e-4, "1e-3": 1e-3}
USED = {"vitb": {"ft": "3e-5", "lora": "1e-4"}, "swinb": {"ft": "1e-5", "lora": "1e-4"}}   # rates of the main comparison
LR_METH = (("ft", "cFT", "square*", "solid", "full fine-tuning"), ("lora", "cAttn", "*", "densely dashed", "LoRA (attention)"))
LR_LEG = ("legend style={font=\\figLegendFont, draw=none, fill=none, at={(-0.12,-0.3)}, anchor=north, legend columns=-1, "
          "/tikz/every even column/.append style={column sep=8pt}}")


def lr_panel(m, key):
    out = ""
    for meth, col, mark, style, lab in LR_METH:
        d = S["lr3"][m][meth]
        pts = " ".join(f"({RATES[r]:g},{s[key][0]:.4f}) +- (0,{s[key][1]:.4f})" for r, s in d.items() if s)
        out += (f"\\addplot[{col}, {style}, thick, mark={mark}, mark size=1.8pt, forget plot, error bars/.cd, y dir=both, "
                f"y explicit] coordinates {{{pts}}};\n")
        u = USED[m][meth]
        out += (f"\\addplot[cAccent, only marks, mark=o, mark size=4.5pt, very thick, forget plot] "
                f"coordinates {{({RATES[u]:g},{d[u][key][0]:.4f})}};\n")
    return out


def lr_legend():
    out = ""
    for meth, col, mark, style, lab in LR_METH:
        out += f"\\addlegendimage{{{col}, {style}, thick, mark={mark}, mark size=1.8pt}}\n\\addlegendentry{{{lab}}}\n"
    out += ("\\addlegendimage{cAccent, only marks, mark=o, mark size=3.5pt, very thick}\n"
            "\\addlegendentry{rate used}\n"
            "\\addlegendimage{cGrey, mark=|, mark size=3pt}\n\\addlegendentry{$\\pm$ std, 3 seeds}\n")
    return out


