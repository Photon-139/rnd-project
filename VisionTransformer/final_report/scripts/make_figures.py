def group(cols, extra="", rows=1, hsep="\\figSep", vsep="1.3cm"):
    return (f"\\begin{{tikzpicture}}\n\\begin{{groupplot}}[group style={{group size={cols} by {rows}, horizontal sep={hsep}, "
            f"vertical sep={vsep}}}, width=\\figW, height=\\figH, repaxis, {extra}]\n")


